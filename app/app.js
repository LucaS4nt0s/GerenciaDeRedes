// Sobe o servidor e, se a porta padrão estiver ocupada, tenta a próxima disponível.
function startServer(port) {
	const server = app.listen(port, () => {
		const appUrl = `http://localhost:${port}`;
		console.log(JSON.stringify({
			level: 'info',
			event: 'server_started',
			port,
			url: appUrl,
			login_failure_incident: incidentState.loginFailureEnabled,
			latency_incident: incidentState.latencyEnabled
		}));
		console.log(`Application is up at ${appUrl}`);
	});

	server.on('error', (error) => {
		if (error.code === 'EADDRINUSE' && !process.env.PORT) {
			const nextPort = port + 1;
			console.error(JSON.stringify({
				level: 'error',
				event: 'port_in_use_retry',
				message: `Port ${port} busy, retrying on ${nextPort}`
			}));
			startServer(nextPort);
			return;
		}

		console.error(JSON.stringify({
			level: 'error',
			event: 'server_start_failed',
			port,
			message: error.message
		}));
		process.exitCode = 1;
	});
}
