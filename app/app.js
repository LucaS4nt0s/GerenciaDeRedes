// Garante que números vindos da query/body fiquem dentro de uma faixa segura.
function clampNumber(value, fallback, min, max) {
	const parsed = Number(value);
	if (!Number.isFinite(parsed)) {
		return fallback;
	}
	return Math.min(max, Math.max(min, parsed));
}

// Aceita vários formatos comuns para booleanos em payloads e query params.
function parseBoolean(value, fallback = false) {
	if (value === undefined || value === null) {
		return fallback;
	}
	if (typeof value === 'boolean') {
		return value;
	}
	if (typeof value === 'string') {
		const normalized = value.trim().toLowerCase();
		if (['true', '1', 'yes', 'on'].includes(normalized)) {
			return true;
		}
		if (['false', '0', 'no', 'off'].includes(normalized)) {
			return false;
		}
	}
	return Boolean(value);
}

// Normaliza o nome da rota para uso nas métricas.
function routeLabel(req) {
	if (req.route && req.route.path) {
		const routePath = Array.isArray(req.route.path) ? req.route.path[0] : req.route.path;
		return `${req.baseUrl || ''}${routePath}`;
	}
	return req.originalUrl ? req.originalUrl.split('?')[0] : req.path;
}

// Remove eventos antigos da janela de 1 minuto.
function trimWindow(now = Date.now()) {
	const cutoff = now - 60000;
	while (requestTimestamps.length > 0 && requestTimestamps[0] < cutoff) {
		requestTimestamps.shift();
	}
	while (errorTimestamps.length > 0 && errorTimestamps[0] < cutoff) {
		errorTimestamps.shift();
	}
}

// Atualiza as métricas derivadas com base nos eventos recentes.
function updateDerivedMetrics(now = Date.now()) {
	trimWindow(now);
	const requestsLastMinute = requestTimestamps.length;
	const errorsLastMinute = errorTimestamps.length;
	errorsPerMinuteGauge.set(errorsLastMinute);
	errorRateGauge.set(requestsLastMinute > 0 ? (errorsLastMinute / requestsLastMinute) * 100 : 0);
}

// Registra um erro na janela móvel e recalcula os indicadores derivados.
function recordError(now = Date.now()) {
	appErrors.inc();
	errorTimestamps.push(now);
	updateDerivedMetrics(now);
}

// Não aplicamos latência artificial em rotas operacionais ou internas.
function shouldBypassLatency(req) {
	const pathName = req.path || '';
	return pathName === '/metrics' || pathName === '/simulate-load' || pathName === '/simulate-error' || pathName.startsWith('/internal/incidents') || pathName.startsWith('/health/');
}

// Calcula um delay artificial com jitter para simular instabilidade.
function computeLatencyDelay() {
	const jitter = incidentState.latencyJitterMs > 0 ? Math.floor((Math.random() * 2 - 1) * incidentState.latencyJitterMs) : 0;
	return Math.max(0, incidentState.latencyDelayMs + jitter);
}

// Middleware de finalização: mede duração, conta requisições e escreve log da resposta.
function applyResponseMetrics(req, res, startedAt) {
	const durationSeconds = Number(process.hrtime.bigint() - startedAt) / 1e9;
	const statusCode = res.statusCode;
	const route = routeLabel(req);

	httpRequestDuration.labels(req.method, route, String(statusCode)).observe(durationSeconds);
	httpRequestsTotal.labels(req.method, route, String(statusCode)).inc();

	const completedAt = Date.now();
	requestTimestamps.push(completedAt);
	if (statusCode >= 400) {
		recordError(completedAt);
	} else {
		updateDerivedMetrics(completedAt);
	}

	console.log(JSON.stringify({
		level: 'info',
		event: 'request_completed',
		correlation_id: req.correlationId,
		method: req.method,
		route,
		status: statusCode,
		duration_ms: Number((durationSeconds * 1000).toFixed(2))
	}));
}

// Captura o tempo total de cada requisição e agenda a gravação das métricas ao final.
app.use((req, res, next) => {
	const startedAt = process.hrtime.bigint();
	res.on('finish', () => applyResponseMetrics(req, res, startedAt));
	next();
});

