// Autenticação simples. Quando o incidente está ativo, devolve 500 de forma proposital.
app.post('/login', (req, res) => {
	const username = typeof req.body?.username === 'string' ? req.body.username.trim() : '';
	const password = typeof req.body?.password === 'string' ? req.body.password : '';

	if (incidentState.loginFailureEnabled) {
		loginFailures.inc({ reason: 'incident_active' });
		console.error(JSON.stringify({ level: 'error', event: 'login_failed', reason: 'incident_active', user: username }));
		return res.status(500).json({ success: false, error: 'login incident active' });
	}

	const user = users.find((candidate) => candidate.username === username && candidate.password === password);
	if (!user) {
		loginFailures.inc({ reason: 'invalid_credentials' });
		console.error(JSON.stringify({ level: 'error', event: 'login_failed', reason: 'invalid_credentials', user: username }));
		return res.status(401).json({ success: false, error: 'invalid credentials' });
	}

	console.log(JSON.stringify({ level: 'info', event: 'login_success', user: username }));
	return res.json({ success: true });
});

