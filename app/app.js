// Middleware de latência: se o incidente estiver ativo, atrasa a resposta e pode falhar.
app.use((req, res, next) => {
	if (!incidentState.latencyEnabled || shouldBypassLatency(req)) {
		return next();
	}

	const delayMs = computeLatencyDelay();
	setTimeout(() => {
		const failureRate = incidentState.latencyFailureRatePercent / 100;
		if (Math.random() < failureRate) {
			console.error(JSON.stringify({
				level: 'error',
				event: 'latency_incident_failure',
				correlation_id: req.correlationId,
				method: req.method,
				path: req.originalUrl,
				delay_ms: delayMs,
				status: incidentState.latencyFailureStatus
			}));
			return res.status(incidentState.latencyFailureStatus).json({ error: 'artificial latency failure' });
		}

		return next();
	}, delayMs);
});

